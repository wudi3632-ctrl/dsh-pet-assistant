import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { createRequire } from 'node:module';

const root = resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const cli = resolve(dirname(require.resolve('rolldown/package.json')), 'bin', 'cli.js');
const banner = '/**\n * @generated by `npm run build:desktop-core`（scripts/build-desktop-core.mjs），请勿手改。\n * 源文件：src/shared/index.ts。\n */';
execFileSync(
  process.execPath,
  [
    cli, 'src/shared/index.ts', '--platform', 'browser', '--format', 'iife', '--name', 'PetShared',
    '--file', 'runtime/electron-helper/shared-core.js', '--banner', banner,
  ],
  { cwd: root, stdio: 'inherit' },
);
